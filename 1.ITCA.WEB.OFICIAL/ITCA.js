function cargarSeccion(nombre) {

    const contenedor =
    document.getElementById('contenedor-dinamico');

    if (!contenedor) return;

    contenedor.style.opacity = '0';

    setTimeout(() => {

        contenedor.innerHTML =
        secciones[nombre] ||
        secciones['inicio'];

        contenedor.style.opacity = '1';

        window.scrollTo({
            top: contenedor.offsetTop - 120,
            behavior: 'smooth'
        });

    }, 300);

}